-- Independent, private third-party observations. No original mail or broker writes.
BEGIN;
CREATE OR REPLACE FUNCTION public.external_analyst_owner_valid(v text) RETURNS boolean
LANGUAGE sql IMMUTABLE SECURITY INVOKER SET search_path=pg_catalog AS $$
 SELECT v ~ '^[A-Za-z0-9_@.+:\-]{1,128}$'
 AND lower(v) NOT IN ('anon','anonymous','public','none','null','grupo_compartido')
$$;

CREATE OR REPLACE FUNCTION public.external_analyst_json_safe(v jsonb, depth integer DEFAULT 0)
RETURNS boolean LANGUAGE plpgsql IMMUTABLE SECURITY INVOKER SET search_path=pg_catalog AS $$
DECLARE pair record; item jsonb;
BEGIN
 IF depth>24 OR octet_length(v::text)>1000000 THEN RETURN false; END IF;
 IF jsonb_typeof(v)='object' THEN
  FOR pair IN SELECT * FROM jsonb_each(v) LOOP
   IF lower(replace(pair.key,'-','_')) IN ('password','secret','token','access_token','refresh_token',
       'authorization','credentials','recipient','recipients','email','raw_body','raw_email','html_body')
     OR NOT public.external_analyst_json_safe(pair.value,depth+1) THEN RETURN false; END IF;
  END LOOP;
 ELSIF jsonb_typeof(v)='array' THEN
  FOR item IN SELECT * FROM jsonb_array_elements(v) LOOP
   IF NOT public.external_analyst_json_safe(item,depth+1) THEN RETURN false; END IF;
  END LOOP;
 ELSIF jsonb_typeof(v)='string' AND (v#>>'{}') ~ '[^[:space:]@]+@[^[:space:]@]+' THEN RETURN false;
 END IF;
 RETURN true;
END $$;

CREATE TABLE IF NOT EXISTS public.external_analyst_messages (
 owner text NOT NULL CHECK(public.external_analyst_owner_valid(owner)),
 message_key text NOT NULL CHECK(message_key ~ '^[a-f0-9]{64}$'),provider text NOT NULL,
 received_at timestamptz NOT NULL,observed_at timestamptz NOT NULL,
 announced_count integer CHECK(announced_count>=0),extracted_count integer NOT NULL CHECK(extracted_count BETWEEN 0 AND 500),
 issues_json jsonb NOT NULL CHECK(public.external_analyst_json_safe(issues_json)),
 fingerprint text NOT NULL CHECK(fingerprint ~ '^[a-f0-9]{64}$'),
 PRIMARY KEY(owner,message_key),CHECK(received_at<=observed_at));
CREATE TABLE IF NOT EXISTS public.external_analyst_calls (
 owner text NOT NULL CHECK(public.external_analyst_owner_valid(owner)),
 call_id text NOT NULL CHECK(call_id ~ '^[a-f0-9]{64}$'),provider text NOT NULL,
 source_id text NOT NULL CHECK(length(source_id) BETWEEN 1 AND 512),
 first_observed_at timestamptz NOT NULL,original_json jsonb NOT NULL CHECK(public.external_analyst_json_safe(original_json)),
 PRIMARY KEY(owner,call_id),UNIQUE(owner,provider,source_id),
 CHECK(original_json->>'id'=call_id));
CREATE TABLE IF NOT EXISTS public.external_analyst_revisions (
 sequence bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner text NOT NULL,call_id text NOT NULL,revision_id text NOT NULL CHECK(revision_id ~ '^[a-f0-9]{64}$'),
 message_key text NOT NULL,observed_at timestamptz NOT NULL,
 call_json jsonb NOT NULL CHECK(public.external_analyst_json_safe(call_json)),
 UNIQUE(owner,call_id,revision_id),CHECK(call_json->>'id'=call_id),
 FOREIGN KEY(owner,call_id) REFERENCES public.external_analyst_calls(owner,call_id),
 FOREIGN KEY(owner,message_key) REFERENCES public.external_analyst_messages(owner,message_key));
CREATE TABLE IF NOT EXISTS public.external_analyst_events (
 sequence bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner text NOT NULL,call_id text NOT NULL,event_key text NOT NULL CHECK(length(event_key) BETWEEN 1 AND 256),
 occurred_at timestamptz NOT NULL,payload_json jsonb NOT NULL CHECK(public.external_analyst_json_safe(payload_json)),
 UNIQUE(owner,call_id,event_key),FOREIGN KEY(owner,call_id) REFERENCES public.external_analyst_calls(owner,call_id));
CREATE TABLE IF NOT EXISTS public.external_analyst_settings (
 owner text PRIMARY KEY CHECK(public.external_analyst_owner_valid(owner)),
 prefs_json jsonb NOT NULL DEFAULT '{"enabled":false}' CHECK(public.external_analyst_json_safe(prefs_json)),
 cursor_json jsonb NOT NULL DEFAULT '{}' CHECK(public.external_analyst_json_safe(cursor_json)));
CREATE TABLE IF NOT EXISTS public.external_analyst_email_deliveries (
 owner text NOT NULL CHECK(public.external_analyst_owner_valid(owner)),delivery_key text NOT NULL CHECK(length(delivery_key) BETWEEN 1 AND 256),
 status text NOT NULL CHECK(status IN ('reserved','sent','failed','uncertain')),
 report_json jsonb NOT NULL CHECK(public.external_analyst_json_safe(report_json)),
 created_at timestamptz NOT NULL DEFAULT now(),finished_at timestamptz,
 PRIMARY KEY(owner,delivery_key));
CREATE TABLE IF NOT EXISTS public.external_analyst_simulation_runs (
 sequence bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner text NOT NULL CHECK(public.external_analyst_owner_valid(owner)),run_id text NOT NULL CHECK(length(run_id) BETWEEN 1 AND 256),
 observed_at timestamptz NOT NULL,payload_json jsonb NOT NULL CHECK(public.external_analyst_json_safe(payload_json)),
 UNIQUE(owner,run_id));

CREATE INDEX IF NOT EXISTS external_analyst_revisions_owner_call_idx ON public.external_analyst_revisions(owner,call_id,sequence DESC);
CREATE INDEX IF NOT EXISTS external_analyst_events_owner_call_idx ON public.external_analyst_events(owner,call_id,sequence);

CREATE OR REPLACE FUNCTION public.external_analyst_append_only() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog AS $$
BEGIN RAISE EXCEPTION 'External observations are append-only'; END $$;
DO $$
DECLARE t text;
BEGIN
 FOREACH t IN ARRAY ARRAY['external_analyst_messages','external_analyst_calls','external_analyst_revisions',
   'external_analyst_events','external_analyst_simulation_runs'] LOOP
  EXECUTE format('DROP TRIGGER IF EXISTS external_append_only ON public.%I',t);
  EXECUTE format('CREATE TRIGGER external_append_only BEFORE UPDATE OR DELETE ON public.%I
    FOR EACH ROW EXECUTE FUNCTION public.external_analyst_append_only()',t);
 END LOOP;
 FOREACH t IN ARRAY ARRAY['external_analyst_messages','external_analyst_calls','external_analyst_revisions',
   'external_analyst_events','external_analyst_settings','external_analyst_email_deliveries',
   'external_analyst_simulation_runs'] LOOP
  EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',t);
  EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC,anon,authenticated,service_role',t);
 END LOOP;
END $$;
-- This application authenticates in its server, not with Supabase Auth JWTs.
-- No browser role can read or mutate an owner's recommendations.
GRANT SELECT,INSERT ON public.external_analyst_messages,public.external_analyst_calls,
 public.external_analyst_revisions,public.external_analyst_events,public.external_analyst_simulation_runs TO service_role;
GRANT SELECT,INSERT,UPDATE ON public.external_analyst_settings,public.external_analyst_email_deliveries TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.external_analyst_revisions_sequence_seq,
 public.external_analyst_events_sequence_seq,public.external_analyst_simulation_runs_sequence_seq TO service_role;

CREATE OR REPLACE FUNCTION public.external_analyst_select(p_owner text,p_payload jsonb) RETURNS jsonb
LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog AS $$
DECLARE kind text:=p_payload->>'kind'; output jsonb;
BEGIN
 IF NOT public.external_analyst_owner_valid(p_owner) THEN RAISE EXCEPTION 'Invalid private owner'; END IF;
 IF kind='calls' THEN SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.first_observed_at,t.call_id),'[]') INTO output FROM public.external_analyst_calls t WHERE owner=p_owner;
 ELSIF kind='messages' THEN SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.observed_at,t.message_key),'[]') INTO output FROM public.external_analyst_messages t WHERE owner=p_owner;
 ELSIF kind='revisions' THEN SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.sequence),'[]') INTO output FROM public.external_analyst_revisions t WHERE owner=p_owner;
 ELSIF kind='events' THEN SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.sequence),'[]') INTO output FROM public.external_analyst_events t WHERE owner=p_owner;
 ELSIF kind='settings' THEN SELECT coalesce(jsonb_agg(to_jsonb(t)),'[]') INTO output FROM public.external_analyst_settings t WHERE owner=p_owner;
 ELSIF kind='deliveries' THEN SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.created_at,t.delivery_key),'[]') INTO output FROM public.external_analyst_email_deliveries t WHERE owner=p_owner;
 ELSIF kind='simulations' THEN SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.sequence),'[]') INTO output FROM public.external_analyst_simulation_runs t WHERE owner=p_owner;
 ELSE RAISE EXCEPTION 'Unknown external observation collection';
 END IF;
 RETURN output;
END $$;

CREATE OR REPLACE FUNCTION public.external_analyst_import(p_owner text,p_payload jsonb) RETURNS jsonb
LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog AS $$
DECLARE old_hash text; item jsonb; c jsonb; prior text; n integer; inserted integer:=0; revised integer:=0; duplicates integer:=0;
 v_message_key text:=p_payload->>'message_key'; observed timestamptz:=(p_payload->>'observed_at')::timestamptz;
BEGIN
 IF NOT public.external_analyst_owner_valid(p_owner) OR NOT public.external_analyst_json_safe(p_payload)
  OR jsonb_typeof(p_payload->'calls')<>'array' OR jsonb_array_length(p_payload->'calls')>500
  OR (p_payload->>'received_at')::timestamptz>observed THEN RAISE EXCEPTION 'Invalid external message'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended(p_owner,0));
 SELECT fingerprint INTO old_hash FROM public.external_analyst_messages WHERE owner=p_owner AND message_key=v_message_key;
 IF old_hash IS NOT NULL THEN
  IF old_hash<>p_payload->>'fingerprint' THEN RAISE EXCEPTION 'Immutable message differs'; END IF;
  RETURN jsonb_build_object('inserted',0,'revised',0,'duplicates',jsonb_array_length(p_payload->'calls'),'message_duplicate',true);
 END IF;
 IF EXISTS(SELECT 1 FROM jsonb_array_elements(p_payload->'calls') x GROUP BY x#>>'{call,id}' HAVING count(*)>1)
 THEN RAISE EXCEPTION 'Duplicate calls in a message'; END IF;
 INSERT INTO public.external_analyst_messages VALUES(p_owner,v_message_key,p_payload->>'provider',
  (p_payload->>'received_at')::timestamptz,observed,(p_payload->>'announced_count')::integer,
  jsonb_array_length(p_payload->'calls'),p_payload->'issues',p_payload->>'fingerprint');
 FOR item IN SELECT * FROM jsonb_array_elements(p_payload->'calls') LOOP
  c:=item->'call';
  IF c->>'observed_at' IS NULL OR c->>'received_at' IS NULL OR c->>'id' IS NULL
   OR (c->>'observed_at')::timestamptz<>observed OR (c->>'received_at')::timestamptz>observed
   THEN RAISE EXCEPTION 'Invalid revision clock'; END IF;
  SELECT call_id INTO prior FROM public.external_analyst_calls WHERE owner=p_owner AND provider=c->>'provider' AND source_id=c->>'source_id';
  IF prior IS NOT NULL AND prior<>c->>'id' THEN RAISE EXCEPTION 'Call identity changed'; END IF;
  IF prior IS NULL THEN
   INSERT INTO public.external_analyst_calls VALUES(p_owner,c->>'id',c->>'provider',c->>'source_id',observed,c);
   inserted:=inserted+1;
  END IF;
  INSERT INTO public.external_analyst_revisions(owner,call_id,revision_id,message_key,observed_at,call_json)
   VALUES(p_owner,c->>'id',item->>'revision_id',v_message_key,observed,c) ON CONFLICT(owner,call_id,revision_id) DO NOTHING;
  GET DIAGNOSTICS n=ROW_COUNT;
  IF n=0 THEN duplicates:=duplicates+1; ELSIF prior IS NOT NULL THEN revised:=revised+1; END IF;
 END LOOP;
 RETURN jsonb_build_object('inserted',inserted,'revised',revised,'duplicates',duplicates,'message_duplicate',false);
END $$;

CREATE OR REPLACE FUNCTION public.external_analyst_append_event(p_owner text,p_payload jsonb) RETURNS boolean
LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog AS $$
DECLARE old public.external_analyst_events%ROWTYPE; observed timestamptz;
BEGIN
 IF NOT public.external_analyst_owner_valid(p_owner) OR NOT public.external_analyst_json_safe(p_payload)
 THEN RAISE EXCEPTION 'Invalid external event'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended(p_owner,0));
 SELECT first_observed_at INTO observed FROM public.external_analyst_calls WHERE owner=p_owner AND call_id=p_payload->>'call_id';
 IF observed IS NULL OR (p_payload->>'occurred_at')::timestamptz<observed THEN RAISE EXCEPTION 'Event precedes observation'; END IF;
 SELECT * INTO old FROM public.external_analyst_events WHERE owner=p_owner AND call_id=p_payload->>'call_id' AND event_key=p_payload->>'event_key';
 IF FOUND THEN
  IF old.occurred_at<>(p_payload->>'occurred_at')::timestamptz OR old.payload_json<>p_payload->'payload' THEN RAISE EXCEPTION 'Immutable event differs'; END IF;
  RETURN false;
 END IF;
 INSERT INTO public.external_analyst_events(owner,call_id,event_key,occurred_at,payload_json)
 VALUES(p_owner,p_payload->>'call_id',p_payload->>'event_key',(p_payload->>'occurred_at')::timestamptz,p_payload->'payload');
 RETURN true;
END $$;

CREATE OR REPLACE FUNCTION public.external_analyst_settings_write(p_owner text,p_payload jsonb) RETURNS boolean
LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog AS $$
DECLARE v jsonb:=p_payload->'value'; pair record;
BEGIN
 IF NOT public.external_analyst_owner_valid(p_owner) OR NOT public.external_analyst_json_safe(p_payload)
  OR jsonb_typeof(v) IS DISTINCT FROM 'object' THEN RAISE EXCEPTION 'Invalid external settings'; END IF;
 INSERT INTO public.external_analyst_settings(owner) VALUES(p_owner) ON CONFLICT(owner) DO NOTHING;
 IF p_payload->>'kind'='preferences' THEN
  IF v-ARRAY['enabled','commission_eur','spread_bps','slippage_bps']<>'{}'::jsonb
   OR (v?'enabled' AND jsonb_typeof(v->'enabled')<>'boolean') THEN RAISE EXCEPTION 'Invalid preferences'; END IF;
  FOR pair IN SELECT * FROM jsonb_each(v-'enabled') LOOP
   IF jsonb_typeof(pair.value)<>'number' OR (pair.value::text)::numeric<0 OR (pair.value::text)::numeric>1000
    THEN RAISE EXCEPTION 'Invalid simulation costs'; END IF;
  END LOOP;
  UPDATE public.external_analyst_settings SET prefs_json=v WHERE owner=p_owner;
 ELSIF p_payload->>'kind'='cursor' THEN
  IF v-ARRAY['uidvalidity','last_uid','mailbox_hash']<>'{}'::jsonb THEN RAISE EXCEPTION 'Invalid cursor'; END IF;
  FOR pair IN SELECT * FROM jsonb_each(v-'mailbox_hash') LOOP
   IF jsonb_typeof(pair.value) NOT IN ('number','string')
    OR (pair.value#>>'{}') !~ '^[0-9]+$' OR (pair.value#>>'{}')::numeric>4294967295
    THEN RAISE EXCEPTION 'Invalid cursor UID'; END IF;
  END LOOP;
  IF v?'mailbox_hash' AND (jsonb_typeof(v->'mailbox_hash') IS DISTINCT FROM 'string'
   OR v->>'mailbox_hash' !~ '^[a-f0-9]{64}$') THEN RAISE EXCEPTION 'Invalid mailbox hash'; END IF;
  UPDATE public.external_analyst_settings SET cursor_json=v WHERE owner=p_owner;
 ELSE RAISE EXCEPTION 'Unknown setting'; END IF;
 RETURN true;
END $$;

CREATE OR REPLACE FUNCTION public.external_analyst_claim_delivery(p_owner text,p_payload jsonb) RETURNS boolean
LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog AS $$
DECLARE n integer;
BEGIN
 IF NOT public.external_analyst_owner_valid(p_owner) OR NOT public.external_analyst_json_safe(p_payload) THEN RAISE EXCEPTION 'Invalid external delivery'; END IF;
 INSERT INTO public.external_analyst_email_deliveries(owner,delivery_key,status,report_json)
 VALUES(p_owner,p_payload->>'delivery_key','reserved',p_payload->'report') ON CONFLICT(owner,delivery_key) DO NOTHING;
 GET DIAGNOSTICS n=ROW_COUNT; RETURN n=1;
END $$;

CREATE OR REPLACE FUNCTION public.external_analyst_finish_delivery(p_owner text,p_payload jsonb) RETURNS boolean
LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog AS $$
DECLARE old_status text;
BEGIN
 IF NOT public.external_analyst_owner_valid(p_owner) OR p_payload->>'status' NOT IN ('sent','failed','uncertain') THEN RAISE EXCEPTION 'Invalid delivery result'; END IF;
 SELECT status INTO old_status FROM public.external_analyst_email_deliveries WHERE owner=p_owner AND delivery_key=p_payload->>'delivery_key' FOR UPDATE;
 IF old_status IS NULL OR old_status NOT IN ('reserved',p_payload->>'status') THEN RAISE EXCEPTION 'Delivery reservation not available'; END IF;
 UPDATE public.external_analyst_email_deliveries SET status=p_payload->>'status',finished_at=now()
 WHERE owner=p_owner AND delivery_key=p_payload->>'delivery_key' AND status='reserved';
 RETURN true;
END $$;

CREATE OR REPLACE FUNCTION public.external_analyst_save_simulation(p_owner text,p_payload jsonb) RETURNS boolean
LANGUAGE plpgsql SECURITY INVOKER SET search_path=pg_catalog AS $$
DECLARE prior jsonb;
BEGIN
 IF NOT public.external_analyst_owner_valid(p_owner) OR NOT public.external_analyst_json_safe(p_payload) THEN RAISE EXCEPTION 'Invalid external simulation'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended(p_owner,0));
 SELECT payload_json INTO prior FROM public.external_analyst_simulation_runs WHERE owner=p_owner AND run_id=p_payload->>'run_id';
 IF prior IS NOT NULL THEN
  IF prior<>p_payload->'payload' THEN RAISE EXCEPTION 'Immutable simulation differs'; END IF;
  RETURN false;
 END IF;
 INSERT INTO public.external_analyst_simulation_runs(owner,run_id,observed_at,payload_json)
 VALUES(p_owner,p_payload->>'run_id',(p_payload->>'observed_at')::timestamptz,p_payload->'payload');
 RETURN true;
END $$;

