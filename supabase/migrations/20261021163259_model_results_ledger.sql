-- Original four-model result ledger. Deploy explicitly after local validation.
-- No remote connections, old-run rewrites, real holdings, or email sends.
-- SECURITY INVOKER RPCs are available only to the server-side service_role.
begin;

do $preflight$
begin
  if to_regclass('public.paper_simulations') is null
     or to_regclass('public.paper_daily_runs') is null then
    raise exception 'The existing paper schema must be installed first';
  end if;
end
$preflight$;

create table if not exists public.model_result_seasons (
  owner text not null check (btrim(owner) <> '' and lower(owner) not in ('anon','anonymous','public','none','null')),
  namespace text not null check (namespace = 'model-original-v1'),
  season_id text not null check (length(season_id) between 1 and 256),
  strategy_key text not null check (strategy_key in ('A','B','C','D')),
  mode text not null check (mode in ('theoretical','budget')),
  manifest_json jsonb not null check (jsonb_typeof(manifest_json) = 'object'),
  manifest_hash text not null check (manifest_hash ~ '^[a-f0-9]{64}$'),
  paper_simulation_id bigint,
  created_at timestamptz not null default now(),
  primary key (owner,namespace,season_id),
  foreign key (owner,paper_simulation_id) references public.paper_simulations(owner,id)
);

create table if not exists public.model_result_batches (
  sequence bigint generated by default as identity primary key,
  owner text not null, namespace text not null, season_id text not null,
  run_id text not null check (length(run_id) between 1 and 256),
  batch_id text not null check (length(batch_id) between 1 and 256),
  market_date date not null, content_hash text not null check (content_hash ~ '^[a-f0-9]{64}$'),
  previous_hash text not null check (previous_hash ~ '^[a-f0-9]{64}$'),
  head_hash text not null check (head_hash ~ '^[a-f0-9]{64}$'),
  request_json jsonb not null check (jsonb_typeof(request_json) = 'object'),
  last_available_at timestamptz not null, paper_daily_run_id bigint,
  created_at timestamptz not null default now(),
  unique (owner,namespace,season_id,batch_id),
  foreign key (owner,namespace,season_id) references public.model_result_seasons(owner,namespace,season_id),
  foreign key (paper_daily_run_id) references public.paper_daily_runs(id)
);

create table if not exists public.model_result_events (
  sequence bigint generated by default as identity primary key,
  owner text not null, namespace text not null, season_id text not null,
  run_id text not null, batch_id text not null,
  event_id text not null check (length(event_id) between 1 and 256),
  event_type text not null check (event_type in ('observation','decision','order_proposed','order_filled','price_mark','incident','email_delivery')),
  occurred_at timestamptz not null, available_at timestamptz not null,
  payload_json jsonb not null check (jsonb_typeof(payload_json) = 'object'),
  event_hash text not null check (event_hash ~ '^[a-f0-9]{64}$'),
  check (occurred_at <= available_at),
  unique (owner,namespace,season_id,event_id),
  foreign key (owner,namespace,season_id,batch_id) references public.model_result_batches(owner,namespace,season_id,batch_id)
