-- Raw canonical JSON avoids Python/PostgreSQL number-format differences.
-- Both the parsed value AND SHA256 are checked: an unverified claimed hash is
-- never used for conflict detection. Raw bytes remain in request_json evidence.
create or replace function public.model_results_checked_hash(p_raw text,p_value jsonb) returns text
language plpgsql immutable security invoker set search_path = public,pg_temp as $fn$
begin
  if p_raw is null or p_raw::jsonb is distinct from p_value then
    raise exception 'Canonical JSON does not match its payload' using errcode='22023';
  end if;
  return encode(sha256(convert_to(p_raw,'UTF8')),'hex');
end
$fn$;

create or replace function public.model_results_aware(p_value text) returns timestamptz
language plpgsql stable security invoker set search_path = public,pg_temp as $fn$
declare v_at timestamptz;
begin
  if p_value is null or p_value !~ '(Z|[+-][0-9]{2}:[0-9]{2})$' then
    raise exception 'A timezone-aware timestamp is required' using errcode='22023';
  end if;
  v_at := p_value::timestamptz;
  if not isfinite(v_at) then raise exception 'Finite timestamps are required' using errcode='22023'; end if;
  return v_at;
end
$fn$;

create or replace function public.model_results_assert_safe(p_value jsonb) returns void
language plpgsql immutable security invoker set search_path = public,pg_temp as $fn$
declare v_key text; v_nested jsonb;
begin
  if jsonb_typeof(p_value)='object' then
    for v_key,v_nested in select * from jsonb_each(p_value) loop
      if replace(lower(v_key),'-','_') = any(array['password','secret','secret_key','service_role_key','api_key','access_token','refresh_token','authorization','smtp_password','token','api_token','client_secret','private_key','credentials','credential','smtp_user','smtp_username','smtp_token','bearer_token','recipient','recipients','email','email_address','to_address']) then
        raise exception 'Credentials and recipient PII cannot be stored' using errcode='22023';
      end if;
      perform public.model_results_assert_safe(v_nested);
    end loop;
  elsif jsonb_typeof(p_value)='array' then
    for v_nested in select * from jsonb_array_elements(p_value) loop perform public.model_results_assert_safe(v_nested); end loop;
  elsif jsonb_typeof(p_value)='string' and (p_value#>>'{}') ~ '[^[:space:]@]+@[^[:space:]@]+' then
    raise exception 'Email addresses cannot be stored' using errcode='22023';
  end if;
end
$fn$;

create or replace function public.model_results_assert_scope(p_request jsonb) returns void
language plpgsql immutable security invoker set search_path = public,pg_temp as $fn$
begin
  if jsonb_typeof(p_request) is distinct from 'object'
    or coalesce(btrim(p_request->>'owner'),'')=''
    or lower(btrim(p_request->>'owner')) in ('anon','anonymous','public','none','null')
    or p_request->>'namespace' is distinct from 'model-original-v1' then
    raise exception 'A non-anonymous owner and original-model namespace are required' using errcode='22023';
  end if;
end
$fn$;

create or replace function public.model_results_assert_finite(p_value jsonb,p_fields text[]) returns void
language plpgsql immutable security invoker set search_path = public,pg_temp as $fn$
declare v_key text; v_number double precision;
begin
  foreach v_key in array p_fields loop
    if p_value ? v_key and p_value->v_key <> 'null'::jsonb then
      if jsonb_typeof(p_value->v_key) is distinct from 'number' then raise exception 'Model money fields require finite JSON numbers' using errcode='22023'; end if;
      v_number := (p_value->>v_key)::double precision;
      if not (v_number>'-Infinity'::double precision and v_number<'Infinity'::double precision) then
        raise exception 'Model money fields require finite JSON numbers' using errcode='22023';
      end if;
    end if;
  end loop;
end
$fn$;

create or replace function public.model_results_assert_conversion(p_native jsonb,p_eur jsonb,p_rate double precision) returns void
language plpgsql immutable security invoker set search_path = public,pg_temp as $fn$
declare v_native double precision; v_eur double precision;
begin
  if jsonb_typeof(p_native) is distinct from 'number' or jsonb_typeof(p_eur) is distinct from 'number' then
    raise exception 'An EUR projection requires observed native amounts' using errcode='22023';
  end if;
  v_native := (p_native#>>'{}')::double precision; v_eur := (p_eur#>>'{}')::double precision;
  if not (abs(v_eur-v_native*p_rate)<=greatest(0.000001,abs(v_native*p_rate)*0.00000001)) then
    raise exception 'The EUR projection does not match its observed USD/EUR rate' using errcode='22023';
  end if;
end
$fn$;

create or replace function public.model_results_create_season(p_request jsonb) returns jsonb
language plpgsql security invoker set search_path = public,pg_temp as $fn$
declare
  v_owner text := p_request->>'owner'; v_ns text := p_request->>'namespace';
  v_id text := p_request->>'season_id'; v_manifest jsonb := p_request->'manifest';
  v_hash text; v_header jsonb := nullif(p_request->'paper_header','null'::jsonb);
  v_old public.model_result_seasons%rowtype; v_paper_id bigint; v_nav double precision;
  v_fx jsonb; v_rate double precision;
begin
  perform public.model_results_assert_scope(p_request);
  if coalesce(length(v_id),0) not between 1 and 256 or jsonb_typeof(v_manifest) is distinct from 'object' then
    raise exception 'A season identity and manifest are required' using errcode='22023';
  end if;
  v_hash := public.model_results_checked_hash(p_request->>'manifest_canonical',v_manifest);
  if v_hash is distinct from p_request->>'manifest_hash' then raise exception 'Manifest hash mismatch' using errcode='22023'; end if;
  perform public.model_results_assert_safe(v_manifest);
  if coalesce(v_manifest->>'strategy_key','') not in ('A','B','C','D')
    or coalesce(v_manifest->>'mode','') not in ('theoretical','budget')
    or coalesce(v_manifest->>'base_currency','') not in ('USD','EUR')
    or coalesce(btrim(v_manifest->>'season_key'),'')=''
    or coalesce(v_manifest->>'start_date','') !~ '^\d{4}-\d{2}-\d{2}$' then
    raise exception 'Invalid strategy, mode, currency or season dates' using errcode='22023';
  end if;
  perform (v_manifest->>'start_date')::date;
  v_nav := (v_manifest->>case when v_manifest->>'base_currency'='USD' then 'initial_nav_usd' else 'initial_nav_eur' end)::double precision;
  if v_nav is null or not (v_nav>=0 and v_nav<'Infinity'::double precision)
    or (v_nav=0 and not (v_manifest->>'base_currency'='USD' and v_manifest->>'mode'='theoretical'
      and coalesce(v_manifest->>'funding_rule','')='external_100_per_entry')) then
    raise exception 'Positive initial NAV is required except zero-funded USD external-entry theory' using errcode='22023';
  end if;
  if v_nav=0 and (coalesce((v_manifest->>'initial_cash_usd')::double precision,0)<>0
    or coalesce(v_manifest->'initial_positions','[]'::jsonb)<>'[]'::jsonb
    or coalesce(v_manifest->'initial_positions_usd','[]'::jsonb)<>'[]'::jsonb) then
    raise exception 'Zero-NAV theory must start without cash or positions' using errcode='22023';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(v_owner||':'||v_ns||':'||v_id,0));
  select * into v_old from public.model_result_seasons where owner=v_owner and namespace=v_ns and season_id=v_id;
  if found then
    if v_old.manifest_hash<>v_hash then raise exception 'The immutable season manifest differs' using errcode='23514'; end if;
    return (to_jsonb(v_old)-'manifest_json')||jsonb_build_object('manifest',v_old.manifest_json);
  end if;
  if v_header is not null then
    perform public.model_results_assert_safe(v_header);
    perform public.model_results_assert_finite(v_header,array['initial_nav_eur','initial_cash_eur']);
    if v_header->>'base_currency' is distinct from 'EUR'
      or (v_manifest->>'base_currency'='USD' and coalesce(v_manifest#>>'{paper_header,fx_observation_id}','')='') then
      raise exception 'USD is not EUR; an observed FX reference is required for an EUR projection' using errcode='22023';
    end if;
    if v_manifest->>'base_currency'='USD' then
      v_fx:=v_manifest->'fx_observation';
      perform public.model_results_assert_finite(v_fx,array['rate_usd_to_eur']);
      v_rate:=(v_fx->>'rate_usd_to_eur')::double precision;
      if v_rate is null or v_rate<=0 or coalesce(btrim(v_fx->>'source'),'')=''
        or v_fx->>'observation_id' is distinct from v_manifest#>>'{paper_header,fx_observation_id}'
        or public.model_results_aware(v_fx->>'available_at')>public.model_results_aware(v_header->>'created_at') then
        raise exception 'A dated, sourced and matching FX observation is required' using errcode='22023';
      end if;
      perform public.model_results_assert_conversion(v_manifest->'initial_nav_usd',v_header->'initial_nav_eur',v_rate);
    end if;
    insert into public.paper_simulations(owner,name,status,base_currency,benchmark_ticker,strategy_key,engine_version,start_date,
      initial_nav_eur,initial_cash_eur,source_snapshot_date,assumptions_json,initial_positions_json,recorded_by,created_at,updated_at)
    values(v_owner,v_header->>'name',v_header->>'status','EUR',v_header->>'benchmark_ticker',v_header->>'strategy_key',v_header->>'engine_version',
      (v_header->>'start_date')::date,(v_header->>'initial_nav_eur')::double precision,(v_header->>'initial_cash_eur')::double precision,
      (v_header->>'source_snapshot_date')::date,(v_header->>'assumptions_json')::jsonb,(v_header->>'initial_positions_json')::jsonb,
      v_owner,public.model_results_aware(v_header->>'created_at'),public.model_results_aware(v_header->>'updated_at')) returning id into v_paper_id;
  end if;
  insert into public.model_result_seasons(owner,namespace,season_id,strategy_key,mode,manifest_json,manifest_hash,paper_simulation_id)
  values(v_owner,v_ns,v_id,v_manifest->>'strategy_key',v_manifest->>'mode',v_manifest,v_hash,v_paper_id) returning * into v_old;
  return (to_jsonb(v_old)-'manifest_json')||jsonb_build_object('manifest',v_old.manifest_json);
end
$fn$;

create or replace function public.model_results_append_batch(p_request jsonb) returns jsonb
language plpgsql security invoker set search_path = public,pg_temp as $fn$
declare
  v_owner text := p_request->>'owner'; v_ns text := p_request->>'namespace'; v_sid text := p_request->>'season_id';
  v_run text := p_request->>'run_id'; v_bid text := p_request->>'batch_id'; v_date date;
  v_content text; v_expected text := p_request->>'expected_previous_hash';
  v_season public.model_result_seasons%rowtype; v_prior public.model_result_batches%rowtype;
  v_head text := repeat('0',64); v_previous text; v_watermark timestamptz := '-infinity';
  v_events jsonb := p_request->'events'; v_fresh jsonb := '[]'; v_seen jsonb := '{}';
  v_event jsonb; v_hash text; v_known text; v_eid text; v_at timestamptz; v_occ timestamptz; v_payload jsonb;
  v_snapshot jsonb := nullif(p_request->'snapshot','null'::jsonb); v_snapold public.model_result_snapshots%rowtype;
  v_snapnew boolean := false; v_snaphash text; v_paperhash text; v_paper jsonb := nullif(p_request->'paper_snapshot','null'::jsonb);
  v_paper_id bigint; v_count integer := 0; v_signal timestamptz;
  v_fx jsonb; v_fx_at timestamptz; v_rate double precision; v_metric text;
begin
  perform public.model_results_assert_scope(p_request);
  if coalesce(length(v_sid),0) not between 1 and 256 or coalesce(length(v_run),0) not between 1 and 256
    or coalesce(length(v_bid),0) not between 1 and 256 or coalesce(p_request->>'market_date','') !~ '^\d{4}-\d{2}-\d{2}$'
    or jsonb_typeof(v_events) is distinct from 'array' then
    raise exception 'Invalid append identities, date or events' using errcode='22023';
  end if;
  v_date := (p_request->>'market_date')::date;
  if jsonb_array_length(v_events)=0 and v_snapshot is null then raise exception 'An event or snapshot is required' using errcode='22023'; end if;
  if v_expected is not null and v_expected !~ '^[a-f0-9]{64}$' then raise exception 'Invalid expected ledger head' using errcode='22023'; end if;
  v_content := public.model_results_checked_hash(p_request->>'content_canonical',p_request-array['content_hash','content_canonical','batch_id','expected_previous_hash']);
  if v_content is distinct from p_request->>'content_hash' then raise exception 'Batch content hash mismatch' using errcode='22023'; end if;
  perform pg_advisory_xact_lock(hashtextextended(v_owner||':'||v_ns||':'||v_sid,0));
  select * into v_season from public.model_result_seasons where owner=v_owner and namespace=v_ns and season_id=v_sid;
  if not found then raise exception 'The model season does not exist for this owner' using errcode='22023'; end if;
  select * into v_prior from public.model_result_batches where owner=v_owner and namespace=v_ns and season_id=v_sid and batch_id=v_bid;
  if found then
    if v_prior.content_hash<>v_content then raise exception 'The immutable batch identity differs' using errcode='23514'; end if;
    return jsonb_build_object('run_id',v_prior.run_id,'batch_id',v_bid,'head_hash',v_prior.head_hash,'previous_hash',v_prior.previous_hash,
      'inserted_events',0,'no_op',true,'paper_daily_run_id',v_prior.paper_daily_run_id);
  end if;
  select * into v_prior from public.model_result_batches where owner=v_owner and namespace=v_ns and season_id=v_sid order by sequence desc limit 1;
  if found then v_head:=v_prior.head_hash; v_watermark:=v_prior.last_available_at; end if;
  if exists(select 1 from public.model_result_batches where owner=v_owner and namespace=v_ns and season_id=v_sid and run_id=v_run and market_date<>v_date) then
    raise exception 'A run identity cannot move to a different market date' using errcode='23514';
  end if;
  for v_event in select * from jsonb_array_elements(v_events) loop
    if jsonb_typeof(v_event) is distinct from 'object' then raise exception 'Event must be an object' using errcode='22023'; end if;
    v_eid := v_event->>'event_id';
    if coalesce(length(v_eid),0) not between 1 and 256
      or coalesce(v_event->>'event_type','') not in ('observation','decision','order_proposed','order_filled','price_mark','incident','email_delivery')
      or jsonb_typeof(v_event->'payload') is distinct from 'object' then raise exception 'Invalid typed event' using errcode='22023'; end if;
    v_hash := public.model_results_checked_hash(v_event->>'event_canonical',v_event-array['event_hash','event_canonical']);
    if v_hash is distinct from v_event->>'event_hash' then raise exception 'Event hash mismatch' using errcode='22023'; end if;
    v_at := public.model_results_aware(v_event->>'available_at'); v_occ := public.model_results_aware(v_event->>'occurred_at');
    if v_occ>v_at then raise exception 'Availability precedes occurrence' using errcode='22023'; end if;
    v_payload := v_event->'payload'; perform public.model_results_assert_safe(v_payload);
    if v_event->>'event_type'='email_delivery' then
      if coalesce(v_payload->>'status','') not in ('planned','attempted','failed','smtp_accepted') or coalesce(btrim(v_payload->>'delivery_id'),'')='' then
        raise exception 'SMTP acceptance and actual delivery must remain distinct' using errcode='22023';
      end if;
      if v_payload->>'status'='smtp_accepted' then
        if v_payload->>'smtp_code' is distinct from '250' or coalesce(v_payload->>'receipt_hash','') !~ '^[a-f0-9]{64}$'
          or public.model_results_aware(v_payload->>'accepted_at')>v_at then
          raise exception 'SMTP acceptance requires a dated hashed acceptance receipt and code 250' using errcode='22023';
        end if;
      end if;
    end if;
    select event_hash into v_known from public.model_result_events where owner=v_owner and namespace=v_ns and season_id=v_sid and event_id=v_eid;
    v_known:=coalesce(v_known,v_seen->>v_eid);
    if v_known is not null then
      if v_known<>v_hash then raise exception 'The immutable event identity differs' using errcode='23514'; end if;
      continue;
    end if;
    if v_at<v_watermark then raise exception 'Availability clocks cannot move backwards' using errcode='23514'; end if;
    v_watermark:=v_at; v_seen:=jsonb_set(v_seen,array[v_eid],to_jsonb(v_hash),true); v_fresh:=v_fresh||jsonb_build_array(v_event);
  end loop;
  if v_paper is not null and v_snapshot is null then raise exception 'A paper projection needs an authoritative model snapshot' using errcode='22023'; end if;
  -- Hash of paper kwargs uses the same canonical bytes embedded in the batch.
  -- They are only an optional EUR projection, never authoritative USD history.
  if v_paper is not null then
    v_paperhash:=public.model_results_checked_hash(p_request->>'paper_snapshot_canonical',v_paper);
  end if;
  if v_snapshot is not null then
    if jsonb_typeof(v_snapshot->'payload') is distinct from 'object' then raise exception 'Invalid snapshot payload' using errcode='22023'; end if;
    v_snaphash:=public.model_results_checked_hash(v_snapshot->>'snapshot_canonical',v_snapshot->'payload');
    if v_snaphash is distinct from v_snapshot->>'snapshot_hash' then raise exception 'Snapshot hash mismatch' using errcode='22023'; end if;
    perform public.model_results_assert_safe(v_snapshot->'payload');
    v_at:=public.model_results_aware(v_snapshot->>'available_at');
    if v_at is distinct from public.model_results_aware(v_snapshot#>>'{payload,available_at}') then raise exception 'Snapshot availability mismatch' using errcode='22023'; end if;
    select * into v_snapold from public.model_result_snapshots where owner=v_owner and namespace=v_ns and season_id=v_sid and run_id=v_run;
    if found then
      if v_snapold.snapshot_hash<>v_snaphash or v_snapold.paper_snapshot_hash is distinct from v_paperhash or v_snapold.market_date<>v_date then
        raise exception 'The daily snapshot is immutable' using errcode='23514';
      end if;
    else
      v_snapnew:=true;
      if v_at<v_watermark then raise exception 'Snapshot availability precedes committed facts' using errcode='23514'; end if;
      v_watermark:=v_at;
    end if;
  end if;
  if jsonb_array_length(v_fresh)=0 and not v_snapnew then
    return jsonb_build_object('run_id',v_run,'batch_id',v_bid,'head_hash',v_head,'previous_hash',v_head,'inserted_events',0,'no_op',true,'paper_daily_run_id',null);
  end if;
  if v_expected is not null and v_expected<>v_head then raise exception 'Stale model ledger head; reload before appending' using errcode='23514'; end if;
  if v_paper is not null and v_snapnew then
    perform public.model_results_assert_safe(v_paper);
    perform public.model_results_assert_finite(v_paper,array['cash_eur','net_nav_eur','hold_nav_eur','benchmark_nav_eur','realized_pnl_eur','unrealized_pnl_eur','cumulative_costs_eur','tax_reserve_eur','coverage_pct','hold_coverage_pct','benchmark_coverage_pct']);
    if v_season.paper_simulation_id is null or (v_season.manifest_json->>'base_currency'='USD' and coalesce(v_paper->>'fx_observation_id','')='') then
      raise exception 'An observed-EUR header and FX reference are required for a USD projection' using errcode='22023';
    end if;
    if v_season.manifest_json->>'base_currency'='USD' then
      select e->'payload',public.model_results_aware(e->>'available_at') into v_fx,v_fx_at
        from jsonb_array_elements(v_fresh) e where e->>'event_id'=v_paper->>'fx_observation_id' and e->>'event_type' in ('observation','price_mark') limit 1;
      if v_fx is null then
        select payload_json,available_at into v_fx,v_fx_at from public.model_result_events
          where owner=v_owner and namespace=v_ns and season_id=v_sid and event_id=v_paper->>'fx_observation_id' and event_type in ('observation','price_mark');
      end if;
      perform public.model_results_assert_finite(v_fx,array['rate_usd_to_eur']);
      v_rate:=(v_fx->>'rate_usd_to_eur')::double precision;
      if v_fx is null or v_rate is null or v_rate<=0 or coalesce(btrim(v_fx->>'source'),'')='' or v_fx_at>public.model_results_aware(v_snapshot->>'available_at') then
        raise exception 'The EUR snapshot requires a prior observed FX ledger event' using errcode='22023';
      end if;
      foreach v_metric in array array['cash','net_nav','hold_nav','benchmark_nav','realized_pnl','unrealized_pnl','cumulative_costs','tax_reserve'] loop
        if v_paper ? (v_metric||'_eur') then
          perform public.model_results_assert_conversion(v_snapshot->'payload'->(v_metric||'_usd'),v_paper->(v_metric||'_eur'),v_rate);
        end if;
      end loop;
    end if;
    v_signal:=case when v_paper->>'signal_as_of' is null then null else public.model_results_aware(v_paper->>'signal_as_of') end;
    insert into public.paper_daily_runs(owner,simulation_id,market_date,signal_as_of,input_hash,status,
      proposed_actions_json,executed_actions_json,positions_after_json,cash_eur,net_nav_eur,hold_nav_eur,benchmark_nav_eur,
      realized_pnl_eur,unrealized_pnl_eur,cumulative_costs_eur,tax_reserve_eur,coverage_pct,hold_coverage_pct,benchmark_coverage_pct,warnings_json,rejected_json,engine_version)
    values(v_owner,v_season.paper_simulation_id,v_date,v_signal,v_paper->>'input_hash',coalesce(v_paper->>'status','complete'),
      coalesce(v_paper->'proposed_actions','[]'),coalesce(v_paper->'executed_actions','[]'),v_paper->'positions_after',
      (v_paper->>'cash_eur')::double precision,(v_paper->>'net_nav_eur')::double precision,(v_paper->>'hold_nav_eur')::double precision,(v_paper->>'benchmark_nav_eur')::double precision,
      coalesce((v_paper->>'realized_pnl_eur')::double precision,0),coalesce((v_paper->>'unrealized_pnl_eur')::double precision,0),
      coalesce((v_paper->>'cumulative_costs_eur')::double precision,0),coalesce((v_paper->>'tax_reserve_eur')::double precision,0),coalesce((v_paper->>'coverage_pct')::double precision,0),
      (v_paper->>'hold_coverage_pct')::double precision,(v_paper->>'benchmark_coverage_pct')::double precision,
      coalesce(v_paper->'warnings','[]'),coalesce(v_paper->'rejected','[]'),coalesce(v_paper->>'engine_version','paper-v1')) returning id into v_paper_id;
  end if;
  v_previous:=v_head; v_head:=encode(sha256(convert_to(v_previous||':'||v_content,'UTF8')),'hex');
  insert into public.model_result_batches(owner,namespace,season_id,run_id,batch_id,market_date,content_hash,previous_hash,head_hash,request_json,last_available_at,paper_daily_run_id)
  values(v_owner,v_ns,v_sid,v_run,v_bid,v_date,v_content,v_previous,v_head,p_request-'expected_previous_hash',v_watermark,v_paper_id);
  for v_event in select * from jsonb_array_elements(v_fresh) loop
    insert into public.model_result_events(owner,namespace,season_id,run_id,batch_id,event_id,event_type,occurred_at,available_at,payload_json,event_hash)
    values(v_owner,v_ns,v_sid,v_run,v_bid,v_event->>'event_id',v_event->>'event_type',public.model_results_aware(v_event->>'occurred_at'),
      public.model_results_aware(v_event->>'available_at'),v_event->'payload',v_event->>'event_hash');
    v_count:=v_count+1;
  end loop;
  if v_snapnew then
    insert into public.model_result_snapshots(owner,namespace,season_id,run_id,market_date,batch_id,available_at,snapshot_json,snapshot_hash,paper_snapshot_hash)
    values(v_owner,v_ns,v_sid,v_run,v_date,v_bid,public.model_results_aware(v_snapshot->>'available_at'),v_snapshot->'payload',v_snaphash,v_paperhash);
  end if;
  return jsonb_build_object('run_id',v_run,'batch_id',v_bid,'head_hash',v_head,'previous_hash',v_previous,'inserted_events',v_count,'no_op',false,'paper_daily_run_id',v_paper_id);
end
$fn$;

create or replace function public.model_results_select(p_request jsonb) returns jsonb
language plpgsql stable security invoker set search_path = public,pg_temp as $fn$
declare v_owner text:=p_request->>'owner'; v_ns text:=p_request->>'namespace'; v_sid text:=p_request->>'season_id'; v_run text:=p_request->>'run_id'; v_rows jsonb;
begin
  perform public.model_results_assert_scope(p_request);
  case p_request->>'kind'
  when 'seasons' then
    if v_run is not null then raise exception 'Season selection does not take run_id' using errcode='22023'; end if;
    select jsonb_agg((to_jsonb(s)-'manifest_json')||jsonb_build_object('manifest',s.manifest_json) order by season_id) into v_rows
      from public.model_result_seasons s where owner=v_owner and namespace=v_ns and (v_sid is null or season_id=v_sid);
  when 'batches' then
    select jsonb_agg((to_jsonb(b)-'request_json')||jsonb_build_object('request',b.request_json) order by sequence) into v_rows
      from public.model_result_batches b where owner=v_owner and namespace=v_ns and (v_sid is null or season_id=v_sid) and (v_run is null or run_id=v_run);
  when 'events' then
    select jsonb_agg((to_jsonb(e)-'payload_json')||jsonb_build_object('payload',e.payload_json) order by sequence) into v_rows
      from public.model_result_events e where owner=v_owner and namespace=v_ns and (v_sid is null or season_id=v_sid) and (v_run is null or run_id=v_run);
  when 'snapshots' then
    select jsonb_agg((to_jsonb(s)-'snapshot_json')||jsonb_build_object('snapshot',s.snapshot_json,'commit_sequence',b.sequence) order by s.market_date,b.sequence) into v_rows
      from public.model_result_snapshots s join public.model_result_batches b
      on b.owner=s.owner and b.namespace=s.namespace and b.season_id=s.season_id and b.batch_id=s.batch_id
      where s.owner=v_owner and s.namespace=v_ns and (v_sid is null or s.season_id=v_sid) and (v_run is null or s.run_id=v_run);
  else raise exception 'Unknown model result selection' using errcode='22023';
  end case;
  return coalesce(v_rows,'[]'::jsonb);
end
$fn$;

