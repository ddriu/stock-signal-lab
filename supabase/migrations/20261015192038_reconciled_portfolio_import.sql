-- Additive, service-only accounting imports. No replacement/deletion of manual
-- operations, account totals, private investments or historical snapshots.
begin;

do $$
begin
    if to_regclass('public.operations') is null
       or to_regclass('public.portfolio_snapshots') is null
       or to_regclass('public.portfolio_accounts') is null
       or to_regclass('public.private_investments') is null then
        raise exception 'Install the base accounting schema before the reconciled import migration';
    end if;
end $$;

alter table public.operations
    add column if not exists source_event_id text,
    add column if not exists settlement_amount_local double precision;

alter table public.operations
    drop constraint if exists operations_source_event_id_check,
    drop constraint if exists operations_settlement_amount_local_check;
alter table public.operations
    add constraint operations_source_event_id_check
        check (source_event_id is null or char_length(source_event_id) between 1 and 200),
    add constraint operations_settlement_amount_local_check
        check (settlement_amount_local is null or
            (settlement_amount_local > 0 and settlement_amount_local::text not in ('NaN','Infinity','-Infinity')));

create unique index if not exists operations_owner_source_event_id_idx
    on public.operations(owner,source_event_id)
    where source_event_id is not null and source_event_id <> '';
create index if not exists operations_reconciled_match_idx
    on public.operations(owner,lower(account_name),upper(ticker),side,upper(currency),quantity,price);

create table if not exists public.portfolio_import_batches (
    id bigint generated by default as identity primary key,
    owner text not null check (char_length(btrim(owner)) between 1 and 120),
    source_sha256 text not null check (source_sha256 ~ '^[a-f0-9]{64}$'),
    snapshot_date date not null,
    metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata)='object'),
    backup jsonb not null check (jsonb_typeof(backup)='object'),
    summary jsonb not null default '{}'::jsonb check (jsonb_typeof(summary)='object'),
    recorded_by text not null default '',
    created_at timestamptz not null default now(),
    constraint portfolio_import_batches_owner_source_unique unique(owner,source_sha256)
);
create index if not exists portfolio_import_batches_owner_created_idx
    on public.portfolio_import_batches(owner,created_at desc,id desc);
alter table public.portfolio_import_batches enable row level security;
revoke all on table public.portfolio_import_batches from public,anon,authenticated;
revoke all on sequence public.portfolio_import_batches_id_seq from public,anon,authenticated;
grant all on table public.portfolio_import_batches to service_role;
grant usage,select on sequence public.portfolio_import_batches_id_seq to service_role;

create or replace function public.import_reconciled_portfolio(
    p_owner text,
    p_bundle jsonb,
    p_recorded_by text default ''
) returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
    v_digest text;
    v_date date;
    v_item jsonb;
    v_op public.operations%rowtype;
    v_saved public.operations%rowtype;
    v_pos public.portfolio_snapshots%rowtype;
    v_existing_pos public.portfolio_snapshots%rowtype;
    v_prior public.portfolio_import_batches%rowtype;
    v_backup jsonb;
    v_metadata jsonb;
    v_pending jsonb := '[]'::jsonb;
    v_preview jsonb := '[]'::jsonb;
    v_summary jsonb;
    v_batch bigint;
    v_max_operation_id bigint;
    v_count integer;
    v_match_id bigint;
    v_reason text;
    v_action text;
    v_ambiguous boolean;
    v_inserted_operations integer := 0;
    v_inserted_positions integer := 0;
    v_skipped_operations integer := 0;
    v_skipped_positions integer := 0;
    v_conflicts integer := 0;
begin
    -- This RPC is intentionally not an authenticated-user endpoint: the trusted
    -- server supplies the authenticated owner, and every read/write scopes it.
    if p_owner is null or char_length(btrim(p_owner)) not between 1 and 120
       or p_owner <> btrim(p_owner) then
        raise exception using errcode='22023',message='A valid owner is required';
    end if;
    if p_bundle is null or jsonb_typeof(p_bundle) <> 'object'
       or octet_length(p_bundle::text) > 20971520 then
        raise exception using errcode='22023',message='Invalid reconciled import bundle';
    end if;
    if exists (select 1 from jsonb_object_keys(p_bundle) k
               where k not in ('source_sha256','snapshot_date','positions','operations','metadata')) then
        raise exception using errcode='22023',message='Unsupported import bundle field';
    end if;
    v_digest := p_bundle->>'source_sha256';
    if v_digest is null or v_digest !~ '^[a-f0-9]{64}$'
       or coalesce(p_bundle->>'snapshot_date','') !~ '^\d{4}-\d{2}-\d{2}$' then
        raise exception using errcode='22023',message='A source hash and snapshot date are required';
    end if;
    v_date := (p_bundle->>'snapshot_date')::date;
    if jsonb_typeof(p_bundle->'positions') is distinct from 'array'
       or jsonb_typeof(p_bundle->'operations') is distinct from 'array'
       or jsonb_typeof(p_bundle->'metadata') is distinct from 'object' then
        raise exception using errcode='22023',message='Invalid import records or metadata';
    end if;
    if jsonb_array_length(p_bundle->'positions') not between 1 and 50000
       or jsonb_array_length(p_bundle->'operations') > 100000 then
        raise exception using errcode='22023',message='Import record limit exceeded';
    end if;
    v_metadata := p_bundle->'metadata';
    if v_metadata::text ~ '(/Users/|/home/|[A-Za-z]:\\)' then
        raise exception using errcode='22023',message='Source filesystem paths must not be stored in import metadata';
    end if;
    if exists (select 1 from jsonb_each(v_metadata) e
        where (e.key in ('events','issues','inventory','checks','fifo_sales','sales_references','position_references','operation_preview','pending_conflicts') and jsonb_typeof(e.value)<>'array')
           or (e.key in ('coverage','provenance') and jsonb_typeof(e.value)<>'object')) then
        raise exception using errcode='22023',message='Invalid import metadata schema';
    end if;
    -- Validate every row before capturing the backup or adding anything.
    for v_item in select value from jsonb_array_elements(p_bundle->'positions') loop
        if jsonb_typeof(v_item)<>'object'
           or coalesce(btrim(v_item->>'platform'),'')=''
           or coalesce(btrim(v_item->>'asset_name'),'')=''
           or (v_item->>'snapshot_date') is distinct from v_date::text then
            raise exception using errcode='22023',message='Invalid snapshot position';
        end if;
        v_pos := jsonb_populate_record(null::public.portfolio_snapshots,v_item);
        if v_pos.value_eur is null or v_pos.value_eur < 0
           or v_pos.value_eur::text in ('NaN','Infinity','-Infinity')
           or v_pos.quantity < 0 or v_pos.quantity::text in ('NaN','Infinity','-Infinity')
           or v_pos.current_price < 0 or v_pos.current_price::text in ('NaN','Infinity','-Infinity')
           or v_pos.cost_estimate_eur < 0 or v_pos.cost_estimate_eur::text in ('NaN','Infinity','-Infinity')
           or v_pos.gain_loss_eur::text in ('NaN','Infinity','-Infinity')
           or v_pos.return_pct::text in ('NaN','Infinity','-Infinity')
           or coalesce(v_pos.currency,'EUR') !~ '^[A-Z]{3}$'
           or char_length(v_pos.platform)>100 or char_length(v_pos.asset_name)>200 then
            raise exception using errcode='22023',message='Invalid snapshot amounts or identifiers';
        end if;
    end loop;
    if exists (select 1 from jsonb_array_elements(p_bundle->'positions') r
               group by r->>'platform',r->>'asset_name' having count(*)>1) then
        raise exception using errcode='22023',message='Duplicate snapshot position';
    end if;
    for v_item in select value from jsonb_array_elements(p_bundle->'operations') loop
        if jsonb_typeof(v_item)<>'object' then
            raise exception using errcode='22023',message='Invalid operation record';
        end if;
        v_op := jsonb_populate_record(null::public.operations,v_item);
        if coalesce(btrim(v_op.source_event_id),'')='' or char_length(v_op.source_event_id)>200
           or coalesce(btrim(v_op.account_name),'')='' or char_length(v_op.account_name)>120
           or coalesce(btrim(v_op.ticker),'')='' or char_length(v_op.ticker)>100
           or v_op.side not in ('Compra','Venta') or v_op.side is null
           or v_op.quantity is null or v_op.quantity<=0 or v_op.quantity::text in ('NaN','Infinity','-Infinity')
           or v_op.price is null or v_op.price<=0 or v_op.price::text in ('NaN','Infinity','-Infinity')
           or v_op.fees is null or v_op.fees<0 or v_op.fees::text in ('NaN','Infinity','-Infinity')
           or v_op.executed_at is null or not isfinite(v_op.executed_at)
           or coalesce(v_op.currency,'') !~ '^[A-Z]{3}$'
           or v_op.settlement_amount_local<=0 or v_op.settlement_amount_local::text in ('NaN','Infinity','-Infinity')
           or v_op.settlement_amount_eur<=0 or v_op.settlement_amount_eur::text in ('NaN','Infinity','-Infinity')
           or v_op.fee_eur<0 or v_op.fee_eur::text in ('NaN','Infinity','-Infinity')
           or v_op.fx_rate_to_eur<=0 or v_op.fx_rate_to_eur::text in ('NaN','Infinity','-Infinity')
           or char_length(coalesce(v_op.notes,''))>20000 then
            raise exception using errcode='22023',message='Invalid operation amounts or identifiers';
        end if;
    end loop;
    if exists (select 1 from jsonb_array_elements(p_bundle->'operations') r
               group by r->>'source_event_id' having count(*)>1) then
        raise exception using errcode='22023',message='Duplicate operation source identity';
    end if;

    perform pg_advisory_xact_lock(hashtextextended('reconciled_portfolio:'||p_owner,0));
    select * into v_prior from public.portfolio_import_batches
        where owner=p_owner and source_sha256=v_digest;
    if found then
        return v_prior.summary||jsonb_build_object('batch_id',v_prior.id,'already_imported',true);
    end if;

    -- Private, owner-scoped full pre-write backup. Never returned by the RPC.
    select jsonb_build_object(
        'operations',(select coalesce(jsonb_agg(to_jsonb(o) order by o.id),'[]'::jsonb) from public.operations o where o.owner=p_owner),
        'portfolio_snapshots',(select coalesce(jsonb_agg(to_jsonb(s) order by s.id),'[]'::jsonb) from public.portfolio_snapshots s where s.owner=p_owner),
        'portfolio_accounts',(select coalesce(jsonb_agg(to_jsonb(a) order by a.id),'[]'::jsonb) from public.portfolio_accounts a where a.owner=p_owner),
        'private_investments',(select coalesce(jsonb_agg(to_jsonb(i) order by i.id),'[]'::jsonb) from public.private_investments i where i.owner=p_owner)
    ) into v_backup;
    select coalesce(max(id),0) into v_max_operation_id from public.operations where owner=p_owner;
    insert into public.portfolio_import_batches(owner,source_sha256,snapshot_date,metadata,backup,summary,recorded_by)
        values(p_owner,v_digest,v_date,v_metadata,v_backup,'{}'::jsonb,lower(btrim(coalesce(p_recorded_by,''))))
        returning id into v_batch;
    v_pending := coalesce(v_metadata->'pending_conflicts','[]'::jsonb);

    for v_item in select value from jsonb_array_elements(p_bundle->'operations') loop
        v_op := jsonb_populate_record(null::public.operations,v_item);
        v_reason := null;
        v_match_id := null;
        v_action := 'insert';
        select count(*),max(o.id) into v_count,v_match_id from public.operations o
        where o.owner=p_owner and o.id<=v_max_operation_id and (
            o.source_event_id=v_op.source_event_id
            or (o.source_event_id is null and left(o.notes,24)='[reconciled-workbook:v1]' and
                strpos(o.notes,'"source_event_id":"'||v_op.source_event_id||'"')>0)
            or (lower(btrim(o.account_name))=lower(btrim(v_op.account_name))
                and upper(o.ticker)=upper(v_op.ticker) and o.side=v_op.side and upper(o.currency)=upper(v_op.currency)
                and (o.executed_at at time zone 'UTC')::date=(v_op.executed_at at time zone 'UTC')::date
                and abs(o.quantity-v_op.quantity)<=0.00000001 and abs(o.price-v_op.price)<=0.000001)
        );
        select exists(select 1 from public.operations o
            where o.owner=p_owner and o.id<=v_max_operation_id and btrim(o.account_name)=''
            and upper(o.ticker)=upper(v_op.ticker) and o.side=v_op.side and upper(o.currency)=upper(v_op.currency)
            and (o.executed_at at time zone 'UTC')::date=(v_op.executed_at at time zone 'UTC')::date
            and abs(o.quantity-v_op.quantity)<=0.00000001 and abs(o.price-v_op.price)<=0.000001)
            into v_ambiguous;
        if v_ambiguous or v_count>1 then
            v_action:='pending'; v_reason:='ambiguous_existing_match';
        elsif v_count=1 then
            select * into v_saved from public.operations where owner=p_owner and id=v_match_id;
            if (v_saved.source_event_id=v_op.source_event_id or
                (left(v_saved.notes,24)='[reconciled-workbook:v1]' and
                 strpos(v_saved.notes,'"source_event_id":"'||v_op.source_event_id||'"')>0)) and (
                upper(v_saved.ticker)<>upper(v_op.ticker) or lower(v_saved.account_name)<>lower(v_op.account_name)
                or v_saved.side<>v_op.side or upper(v_saved.currency)<>upper(v_op.currency)
                or abs(v_saved.quantity-v_op.quantity)>0.00000001 or abs(v_saved.price-v_op.price)>0.00000001
                or (v_saved.executed_at at time zone 'UTC')::date<>(v_op.executed_at at time zone 'UTC')::date) then
                v_action:='pending'; v_reason:='source_event_identity_conflict';
            elsif abs(v_saved.fees-v_op.fees)>0.025
               or abs(v_saved.settlement_amount_local-v_op.settlement_amount_local)>0.025
               or abs(v_saved.settlement_amount_eur-v_op.settlement_amount_eur)>0.025 then
                v_action:='pending'; v_reason:='contradictory_existing_amount';
            else
                v_action:='skip'; v_reason:='existing_economic_event';
            end if;
        else
            select o.id into v_match_id from public.operations o
                where o.owner=p_owner and o.id<=v_max_operation_id
                and lower(btrim(o.account_name))=lower(btrim(v_op.account_name))
                and upper(o.ticker)=upper(v_op.ticker) and o.side=v_op.side and upper(o.currency)=upper(v_op.currency)
                and (o.executed_at at time zone 'UTC')::date=(v_op.executed_at at time zone 'UTC')::date
                and abs(o.quantity-v_op.quantity)<=0.00000001 order by o.id limit 1;
            if found then
                v_action:='pending'; v_reason:='ambiguous_same_day_correction';
            end if;
        end if;
        v_preview:=v_preview||jsonb_build_array(jsonb_build_object('source_event_id',v_op.source_event_id,'action',v_action,'reason',coalesce(v_reason,'new_economic_event'),'existing_id',v_match_id));
        if v_action='pending' then
            v_conflicts:=v_conflicts+1;
            v_pending:=v_pending||jsonb_build_array(jsonb_build_object('kind','operation','source_event_id',v_op.source_event_id,'action','pending','reason',v_reason,'existing_id',v_match_id));
        elsif v_action='skip' then
            v_skipped_operations:=v_skipped_operations+1;
        else
            insert into public.operations(owner,ticker,account_name,side,quantity,price,fees,
                settlement_amount_eur,settlement_amount_local,source_event_id,fee_eur,fx_rate_to_eur,
                executed_at,notes,currency,recorded_by)
            values(p_owner,v_op.ticker,v_op.account_name,v_op.side,v_op.quantity,v_op.price,v_op.fees,
                v_op.settlement_amount_eur,v_op.settlement_amount_local,v_op.source_event_id,v_op.fee_eur,v_op.fx_rate_to_eur,
                v_op.executed_at,coalesce(v_op.notes,''),v_op.currency,lower(btrim(coalesce(p_recorded_by,''))));
            v_inserted_operations:=v_inserted_operations+1;
        end if;
    end loop;

    for v_item in select value from jsonb_array_elements(p_bundle->'positions') loop
        v_pos:=jsonb_populate_record(null::public.portfolio_snapshots,v_item);
        select * into v_existing_pos from public.portfolio_snapshots
            where owner=p_owner and snapshot_date=v_date and platform=v_pos.platform and asset_name=v_pos.asset_name;
        if found then
            if row(v_existing_pos.raw_identifier,v_existing_pos.analysis_ticker,v_existing_pos.asset_type,v_existing_pos.portfolio_block,
                v_existing_pos.quantity,v_existing_pos.current_price,v_existing_pos.currency,v_existing_pos.value_eur,
                v_existing_pos.return_pct,v_existing_pos.cost_estimate_eur,v_existing_pos.gain_loss_eur)
                is not distinct from row(coalesce(v_pos.raw_identifier,''),coalesce(v_pos.analysis_ticker,''),coalesce(v_pos.asset_type,''),coalesce(v_pos.portfolio_block,''),
                v_pos.quantity,v_pos.current_price,coalesce(v_pos.currency,'EUR'),v_pos.value_eur,v_pos.return_pct,v_pos.cost_estimate_eur,v_pos.gain_loss_eur) then
                v_skipped_positions:=v_skipped_positions+1;
            else
                v_conflicts:=v_conflicts+1;
                v_pending:=v_pending||jsonb_build_array(jsonb_build_object('kind','snapshot','reason','existing_snapshot_conflict','existing_id',v_existing_pos.id,'platform',v_pos.platform,'asset_name',v_pos.asset_name));
            end if;
        else
            insert into public.portfolio_snapshots(owner,snapshot_date,platform,asset_name,raw_identifier,analysis_ticker,
                asset_type,portfolio_block,quantity,current_price,currency,value_eur,return_pct,cost_estimate_eur,gain_loss_eur,
                comments,source,notes,recorded_by)
            values(p_owner,v_date,v_pos.platform,v_pos.asset_name,coalesce(v_pos.raw_identifier,''),coalesce(v_pos.analysis_ticker,''),
                coalesce(v_pos.asset_type,''),coalesce(v_pos.portfolio_block,''),v_pos.quantity,v_pos.current_price,
                coalesce(v_pos.currency,'EUR'),v_pos.value_eur,v_pos.return_pct,v_pos.cost_estimate_eur,v_pos.gain_loss_eur,
                coalesce(v_pos.comments,''),coalesce(v_pos.source,''),coalesce(v_pos.notes,''),lower(btrim(coalesce(p_recorded_by,''))));
            v_inserted_positions:=v_inserted_positions+1;
        end if;
    end loop;
    v_metadata:=v_metadata||jsonb_build_object('pending_conflicts',v_pending,'operation_preview',v_preview);
    v_summary:=jsonb_build_object('batch_id',v_batch,'source_sha256',v_digest,
        'inserted_positions',v_inserted_positions,'inserted_operations',v_inserted_operations,
        'skipped_positions',v_skipped_positions,'skipped_operations',v_skipped_operations,
        'pending_conflicts',v_conflicts,'already_imported',false);
    update public.portfolio_import_batches set metadata=v_metadata,summary=v_summary
        where owner=p_owner and id=v_batch;
    return v_summary;
end;
$$;

revoke all on function public.import_reconciled_portfolio(text,jsonb,text) from public,anon,authenticated;
grant execute on function public.import_reconciled_portfolio(text,jsonb,text) to service_role;
commit;
