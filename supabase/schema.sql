-- Diario paper aislado: registra decisiones y valoración simuladas sin tocar
-- operaciones ni fotografías de la cartera real.
create table if not exists public.paper_simulations (
    id bigint generated by default as identity primary key,
    owner text not null,
    name text not null,
    status text not null default 'active'
        check (status in ('active', 'paused', 'archived')),
    base_currency text not null default 'EUR'
        check (char_length(base_currency) = 3),
    benchmark_ticker text not null default 'SPY',
    strategy_key text not null,
    engine_version text not null,
    start_date date not null,
    initial_nav_eur double precision not null check (initial_nav_eur > 0),
    initial_cash_eur double precision not null default 0
        check (initial_cash_eur >= 0),
    source_snapshot_date date,
    assumptions_json jsonb not null default '{}'::jsonb,
    initial_positions_json jsonb not null default '[]'::jsonb,
    recorded_by text not null default '',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (initial_cash_eur <= initial_nav_eur),
    check (jsonb_typeof(assumptions_json) = 'object'),
    check (jsonb_typeof(initial_positions_json) = 'array'),
    constraint paper_simulations_owner_id_unique unique (owner, id)
);

create index if not exists paper_simulations_owner_status_date_idx
    on public.paper_simulations (owner, status, start_date desc, id desc);

alter table public.paper_simulations enable row level security;
revoke all on table public.paper_simulations from anon, authenticated;
grant all on table public.paper_simulations to service_role;
grant usage, select on sequence public.paper_simulations_id_seq to service_role;

