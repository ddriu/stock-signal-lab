create table if not exists public.operations (
    id bigint generated by default as identity primary key,
    owner text not null,
    ticker text not null,
    account_name text not null default '',
    side text not null check (side in ('Compra', 'Venta')),
    quantity double precision not null check (quantity > 0),
    price double precision not null check (price > 0),
    fees double precision not null default 0 check (fees >= 0),
    settlement_amount_eur double precision
        check (settlement_amount_eur is null or settlement_amount_eur > 0),
    fee_eur double precision check (fee_eur is null or fee_eur >= 0),
    fx_rate_to_eur double precision check (fx_rate_to_eur is null or fx_rate_to_eur > 0),
    executed_at timestamptz not null,
    notes text not null default '',
    currency text not null default 'EUR' check (char_length(currency) = 3),
    recorded_by text not null default '',
    created_at timestamptz not null default now()
);

-- Migración segura para instalaciones creadas con una versión anterior.
alter table public.operations
    add column if not exists recorded_by text not null default '';

alter table public.operations
    add column if not exists account_name text not null default '',
    add column if not exists settlement_amount_eur double precision,
    add column if not exists fee_eur double precision,
    add column if not exists fx_rate_to_eur double precision;

create index if not exists operations_owner_executed_idx
    on public.operations (owner, executed_at desc, id desc);

alter table public.operations enable row level security;

-- No se concede acceso a claves públicas. La clave secreta del backend usa
-- service_role y omite RLS; la app filtra siempre por el usuario autenticado.
revoke all on table public.operations from anon, authenticated;
grant all on table public.operations to service_role;
grant usage, select on sequence public.operations_id_seq to service_role;

